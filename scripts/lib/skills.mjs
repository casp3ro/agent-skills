// Shared helpers for building and validating rule-based skills.
// Zero dependencies: Node.js 20+ standard library only.

import { readFileSync, readdirSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

// SKILLS_REPO_ROOT lets the harness tests run the scripts against fixture repositories.
export const REPO_ROOT = process.env.SKILLS_REPO_ROOT || join(dirname(fileURLToPath(import.meta.url)), '..', '..')
export const SKILLS_DIR = join(REPO_ROOT, 'skills')
export const EVALS_DIR = join(REPO_ROOT, 'evals')

export const IMPACT_LEVELS = ['CRITICAL', 'HIGH', 'MEDIUM-HIGH', 'MEDIUM', 'LOW-MEDIUM', 'LOW']

export const QUICK_REFERENCE_START = '<!-- quick-reference:start (generated by `npm run build`, do not edit) -->'
export const QUICK_REFERENCE_END = '<!-- quick-reference:end -->'

/** Normalize line endings so Windows checkouts parse identically. */
export function readText(path) {
  return readFileSync(path, 'utf8').replace(/\r\n/g, '\n')
}

/**
 * Minimal YAML frontmatter parser: `key: value` pairs plus one level of nested
 * maps (enough for SKILL.md `metadata:` and rule files). Quotes are stripped.
 */
export function parseFrontmatter(text) {
  if (!text.startsWith('---\n')) return { data: {}, body: text, hasFrontmatter: false }
  const end = text.indexOf('\n---', 4)
  if (end === -1) return { data: {}, body: text, hasFrontmatter: false }

  const data = {}
  let currentMap = null
  for (const line of text.slice(4, end).split('\n')) {
    if (!line.trim() || line.trim().startsWith('#')) continue
    const nested = line.match(/^\s+([\w-]+):\s*(.*)$/)
    if (nested && currentMap) {
      currentMap[nested[1]] = unquote(nested[2])
      continue
    }
    const top = line.match(/^([\w-]+):\s*(.*)$/)
    if (!top) continue
    if (top[2] === '') {
      currentMap = {}
      data[top[1]] = currentMap
    } else {
      currentMap = null
      data[top[1]] = unquote(top[2])
    }
  }
  const body = text.slice(text.indexOf('\n', end + 1) + 1)
  return { data, body, hasFrontmatter: true }
}

function unquote(value) {
  return value.trim().replace(/^(["'])(.*)\1$/, '$2')
}

/** Skills that use the rules/ layout (rules/_sections.md present). */
export function listRuleSkills() {
  return readdirSync(SKILLS_DIR, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && existsSync(join(SKILLS_DIR, entry.name, 'rules', '_sections.md')))
    .map((entry) => entry.name)
    .sort()
}

/** Every skill directory (anything containing SKILL.md). */
export function listAllSkills() {
  return readdirSync(SKILLS_DIR, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && existsSync(join(SKILLS_DIR, entry.name, 'SKILL.md')))
    .map((entry) => entry.name)
    .sort()
}

/** Parse rules/_sections.md into ordered section objects. */
export function parseSections(skillDir) {
  const text = readText(join(skillDir, 'rules', '_sections.md'))
  const sections = []
  const headingPattern = /^## (\d+)\. (.+?) \(([a-z0-9-]+)\)\s*$/gm
  let match
  while ((match = headingPattern.exec(text))) {
    const start = match.index + match[0].length
    const next = text.slice(start).search(/^## /m)
    const block = next === -1 ? text.slice(start) : text.slice(start, start + next)
    sections.push({
      number: Number(match[1]),
      title: match[2].trim(),
      prefix: match[3],
      impact: (block.match(/\*\*Impact:\*\*\s*([A-Z-]+)/) || [])[1] || '',
      description: ((block.match(/\*\*Description:\*\*\s*(.+)/) || [])[1] || '').trim(),
    })
  }
  return sections
}

/** Parse every rule file (files starting with `_` are skipped). */
export function parseRules(skillDir, sections) {
  const rulesDir = join(skillDir, 'rules')
  const prefixes = [...sections].sort((a, b) => b.prefix.length - a.prefix.length)
  return readdirSync(rulesDir)
    .filter((file) => file.endsWith('.md') && !file.startsWith('_'))
    .sort()
    .map((file) => {
      const raw = readText(join(rulesDir, file))
      const { data, body, hasFrontmatter } = parseFrontmatter(raw)
      const id = file.replace(/\.md$/, '')
      const section = prefixes.find((s) => id.startsWith(`${s.prefix}-`))
      return {
        id,
        file,
        hasFrontmatter,
        title: data.title || '',
        impact: data.impact || '',
        impactDescription: data.impactDescription || '',
        tags: (data.tags || '').split(',').map((t) => t.trim()).filter(Boolean),
        section,
        body: body.trim(),
      }
    })
}

/** Rules grouped by section, sorted alphabetically by title, with generated IDs (1.1, 1.2, ...). */
export function groupRules(sections, rules) {
  return sections.map((section) => {
    const sectionRules = rules
      .filter((rule) => rule.section && rule.section.prefix === section.prefix)
      .sort((a, b) => a.title.localeCompare(b.title))
      .map((rule, index) => ({ ...rule, number: `${section.number}.${index + 1}` }))
    return { ...section, rules: sectionRules }
  })
}

/** Extract labelled code examples: **Incorrect (...):** / **Correct (...):** followed by a fenced block. */
export function extractExamples(body) {
  const examples = []
  const pattern = /^\*\*(Incorrect|Correct)(?: \(([^\n]*?)\))?:\*\*\s*\n+```([\w-]*)\n([\s\S]*?)^```/gm
  let match
  while ((match = pattern.exec(body))) {
    examples.push({
      type: match[1] === 'Incorrect' ? 'bad' : 'good',
      description: match[2] || '',
      language: match[3] || '',
      code: match[4].replace(/\n$/, ''),
    })
  }
  return examples
}

/** GitHub-style heading anchor. */
export function anchor(text) {
  return text
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s-]/gu, '')
    .trim()
    .replace(/\s/g, '-')
}
